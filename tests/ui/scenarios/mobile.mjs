export default async({page,api,expect,shot})=>{
 await api('bots',{name:'University',color:'#86c5f7',shape:'round',eyes:'classic'});
 await page.setViewportSize({width:390,height:844});
 await page.waitForSelector('.mobile-home');
 expect(await page.locator('.sidebar').count()===0,'desktop sidebar is absent on phone');
 await shot('home');
 await page.getByRole('button',{name:'New Bot',exact:true}).click();
 await page.getByLabel('Name your Bot', {exact:true}).fill('Mobile helper');
 await page.getByRole('radio',{name:'Mint',exact:true}).click();
 await page.getByRole('button',{name:'Create',exact:true}).click();
 await page.waitForSelector('.conversation .composer');
 expect((await api('state')).bots.some(b=>b.name==='Mobile helper'&&b.color==='#7fd8b0'),'created bot and saved color');
 await page.getByRole('button',{name:'Back to bots'}).click();
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await page.getByRole('textbox',{name:'Search',exact:true}).fill('University');
 expect(await page.locator('.mobile-bot-row').count()===1,'search filters bot list');
 await shot('search');
 await page.getByRole('button',{name:'Close search'}).click();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Connect apps',exact:true}).click();
 expect(await page.locator('.mobile-sheet-body').innerText()==='','no fake plugins or placeholder content');
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await shot('settings');
 await page.getByRole('button',{name:/Appearance/,exact:true}).click();
 await page.getByRole('radio',{name:'Light',exact:true}).click();
 await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await page.getByRole('button',{name:'Close',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal page overflow');
 await shot('light');
};
